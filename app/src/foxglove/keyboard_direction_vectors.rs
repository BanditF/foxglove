//! The Scenes page's directions on the keyboard, end to end: a look's direction (scene_looks),
//! its SET_EFFECT and PLACE as the app sends them (scene_output, Foxglove link's builders), each
//! LED's place from the board profile (scene_room), and the colour crates/scene gives each LED.
//! The ZMK simulator (tests/zmk-sim/host-effects) renders the same reports on both halves with
//! the firmware's lamp table and mirror (lamp_effect.c) and holds every LED to these colours.
//!
//! The file is generated: after a change to the looks, the room, the board profile or the
//! effects, run
//! `FOXGLOVE_UPDATE_VECTORS=1 cargo test --manifest-path app/Cargo.toml keyboard_direction`
//! and let firmware CI's simulator check the C side against it.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::PathBuf;

use foxglove_scene::{Effect, MonitorInfo, Point, Rgb, RoomMap, SceneTime};

use super::boards::{Board, LED_MAP_CHECKED};
use super::scene_looks::{Direction, Kind, Look};
use super::scene_output::{keyboard_effect, keyboard_frame, KeyboardEffect};

/// The Corne's LEDs per half.
const HALF_LAMPS: usize = 21;

const VECTORS: &str = "tests/zmk-sim/module/direction_vectors.inc";

/// The user's desk: a 1440p monitor and the Corne below it, its LED map taken as checked so
/// every LED is placed. The order is pinned to the column snake that lamp_effect.c's built-in
/// table has (the old provisional map), not the profile's shipped one, so these vectors and the
/// firmware simulator keep agreeing whatever map the profile ships.
fn room() -> RoomMap {
    let devices = super::scene_room::devices(Some(&board()), &[], &BTreeMap::new());
    let monitors = [MonitorInfo {
        id: r"\\.\DISPLAY1".into(),
        primary: true,
        rect_px: [0, 0, 2560, 1440],
        raw_dpi: Some(109),
        dpi: 96,
    }];
    RoomMap::build(&monitors, &devices, &Default::default())
}

/// The Corne's profile with the column snake as its checked map (see [`room`]).
fn board() -> Board {
    let mut board = Board::parse(include_str!("../../resources/boards/eyelash-corne.toml"))
        .expect("the Corne's profile");
    let drawing = board.drawing.clone().unwrap_or_default();
    let lighting = board.lighting.as_mut().expect("lighting");
    lighting.led_keys = super::boards::Lamp::chain(
        &super::led_map_confirm::serpentine(&drawing, HALF_LAMPS).expect("21 keys"),
    );
    lighting.led_map = LED_MAP_CHECKED.into();
    board
}

/// The Corne's LEDs by part, from its profile.
fn parts() -> foxglove_link::lamps::LampParts {
    super::boards::lamp_parts(Some(&board()))
}

/// The looks the page offers with a direction that the keyboard draws itself.
fn looks() -> Vec<(String, Look)> {
    let mut out = Vec::new();
    for kind in [Kind::Scanline, Kind::Sweep] {
        for direction in Direction::ALL {
            let look = Look {
                kind,
                direction,
                ..Look::default()
            };
            out.push((format!("{kind:?} {}", direction.label()), look));
        }
    }
    out
}

/// The unit vector a direction runs along (room space has y down).
fn unit(d: Direction) -> Point {
    match d {
        Direction::Right => Point::new(1.0, 0.0),
        Direction::Down => Point::new(0.0, 1.0),
        Direction::Left => Point::new(-1.0, 0.0),
        Direction::Up => Point::new(0.0, -1.0),
    }
}

/// Every keyboard LED's place in the room, in strip order (left half, then right).
fn lamps(room: &RoomMap) -> Vec<Point> {
    let mut out = Vec::new();
    for id in ["keyboard:left", "keyboard:right"] {
        let d = room.devices.iter().find(|d| d.id == id).expect("a half");
        assert_eq!(d.lights.len(), HALF_LAMPS, "{id}");
        for (i, l) in d.lights.iter().enumerate() {
            assert_eq!(l.id, i.to_string(), "{id} in strip order");
            out.push(l.at);
        }
    }
    out
}

/// The moments a vector is taken at: a period's sixteenths, a few periods in.
fn times(period_ms: u32) -> Vec<i64> {
    let p = i64::from(period_ms);
    (0..16).map(|k| 3 * p + k * p / 16 + 7).collect()
}

fn bytes(b: &[u8]) -> String {
    b.iter().map(u8::to_string).collect::<Vec<_>>().join(", ")
}

fn generate() -> String {
    let room = room();
    let parts = parts();
    let mut out = String::new();
    out.push_str(
        "/* Generated by app/src/foxglove/keyboard_direction_vectors.rs: do not edit. After a\n \
         * change to the looks, the room, the board profile or the effects, run\n \
         * FOXGLOVE_UPDATE_VECTORS=1 cargo test --manifest-path app/Cargo.toml keyboard_direction\n \
         * Each: the PLACE report's room, left and right (mm), the EFFECT report as the app\n \
         * sends it, and the colour crates/scene gives each LED (left 0-20, right 0-20). */\n",
    );
    for (name, look) in looks() {
        let effect = look.effect(&room);
        let ke: KeyboardEffect =
            keyboard_effect(&effect, &room, &parts).expect("the keyboard draws it");
        writeln!(out, "/* {name} */").unwrap();
        let (left, right) = ke.place();
        let place: Vec<String> = ke
            .room
            .iter()
            .chain(&left)
            .chain(&right)
            .map(i16::to_string)
            .collect();
        for t in times(ke.effect.period_ms) {
            let report = foxglove_link::protocol::effect(&ke.at(SceneTime(t))).expect("it fits");
            let mut report32 = report.clone();
            report32.resize(32, 0);
            let frame = effect.render(&room, SceneTime(t));
            let lights: Vec<(&str, &str, Rgb)> = frame
                .lights
                .iter()
                .filter(|l| l.device.starts_with("keyboard"))
                .map(|l| (l.device.as_str(), l.light.as_str(), l.colour))
                .collect();
            let lamps = keyboard_frame(&lights, &parts).expect("both halves").lamps;
            assert_eq!(lamps.len(), 2 * HALF_LAMPS);
            let want = lamps
                .iter()
                .map(|c| format!("{{{}}}", bytes(&c.0)))
                .collect::<Vec<_>>()
                .join(", ");
            writeln!(
                out,
                "{{{{{}}}, {{{}}}, {{{want}}}}},",
                place.join(", "),
                bytes(&report32)
            )
            .unwrap();
        }
    }
    out
}

#[test]
fn keyboard_direction_vectors_are_current() {
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("..")
        .join(VECTORS);
    let want = generate();
    if std::env::var_os("FOXGLOVE_UPDATE_VECTORS").is_some() {
        std::fs::write(&path, &want).unwrap();
        return;
    }
    let have = std::fs::read_to_string(&path)
        .unwrap_or_default()
        .replace("\r\n", "\n");
    assert!(
        have == want,
        "{VECTORS} is out of date: run FOXGLOVE_UPDATE_VECTORS=1 cargo test --manifest-path \
         app/Cargo.toml keyboard_direction"
    );
}

/// Each direction's scanline reaches the keyboard's LEDs in that direction: an LED further
/// along it lights later in the period, on both halves.
#[test]
fn keyboard_direction_scanlines_cross_the_leds_in_order() {
    let room = room();
    let at = lamps(&room);
    for direction in Direction::ALL {
        let look = Look {
            direction,
            ..Look::default()
        };
        let effect = look.effect(&room);
        let (colour, period_ms) = match &effect {
            Effect::Scanline {
                colour, period_ms, ..
            } => (*colour, *period_ms),
            _ => panic!("a scanline"),
        };
        // When the band's centre passes each LED: its colour is nearest the band's then.
        let steps = 4000;
        let peak: Vec<i64> = at
            .iter()
            .map(|p| {
                (0..steps)
                    .map(|k| i64::from(period_ms) * k / steps)
                    .min_by_key(|&t| {
                        let c = effect.colour(*p, SceneTime(t), &room.bounds).0;
                        (0..3)
                            .map(|i| (i32::from(c[i]) - i32::from(colour.0[i])).abs())
                            .sum::<i32>()
                    })
                    .unwrap()
            })
            .collect();
        let u = unit(direction);
        let along = |p: &Point| p.x * u.x + p.y * u.y;
        for (a, pa) in at.iter().enumerate() {
            for (b, pb) in at.iter().enumerate() {
                if along(pb) - along(pa) > 5.0 {
                    assert!(
                        peak[a] < peak[b],
                        "{direction:?}: LED {a} at {pa:?} lights at {} ms, after LED {b} at {pb:?} \
                         at {} ms",
                        peak[a],
                        peak[b]
                    );
                }
            }
        }
    }
}

/// The vectors aren't all background: the band and the sweep cross the keyboard.
#[test]
fn keyboard_direction_vectors_move() {
    let text = generate();
    let rows: std::collections::BTreeSet<&str> = text
        .lines()
        .filter(|l| l.starts_with("{{"))
        .filter_map(|l| l.split_once("}, {{").map(|(_, lamps)| lamps))
        .collect();
    assert!(rows.len() > 8 * 4, "{} distinct frames", rows.len());
}

/// With every LED placed, the effect carries each half's points for EFFECT LAMPS (#550), in
/// thousandths of the half: the profile's key centres are lamp_effect.c's built-in table, the
/// right half its mirror (its own points, not mirrored again on the keyboard).
#[test]
fn keyboard_effect_lamps_are_each_halfs_own_points() {
    let room = room();
    let e = keyboard_effect(&Look::default().effect(&room), &room, &parts()).expect("it maps");
    let [left, right]: [Vec<[u16; 2]>; 2] = e
        .lamps
        .expect("every LED placed")
        .try_into()
        .expect("two halves");
    assert_eq!((left.len(), right.len()), (HALF_LAMPS, HALF_LAMPS));
    // lamp_effect.c lamps_permille: LED 0 {77, 222}, LED 20 {923, 889}.
    let near = |a: [u16; 2], b: [u16; 2]| a[0].abs_diff(b[0]) <= 1 && a[1].abs_diff(b[1]) <= 1;
    assert!(near(left[0], [77, 222]), "{:?}", left[0]);
    assert!(near(left[20], [923, 889]), "{:?}", left[20]);
    assert!(near(right[0], [923, 222]), "{:?}", right[0]);
    assert!(near(right[20], [77, 889]), "{:?}", right[20]);
}
